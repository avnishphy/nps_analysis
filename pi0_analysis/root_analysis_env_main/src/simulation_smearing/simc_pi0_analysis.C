// OUTPUT TREE CONTENT:
// Only events passing ALL cuts are written to the output tree:
//   - HMS electron cuts (hreactz, delta, xptar, yptar)
//   - Photon hit requirements (2 good photon clusters)
//   - NPS spatial and energy cuts
// This ensures consistency with downstream analysis (e.g., nps_sim_smearing_new_try.C)
//
// SMEARING METHODOLOGY (Updated to match nps_sim_smearing_new_try.C):
// Energy mean response:
//   E_mean(E) = a + b*E_safe + c*ln(E_safe/1 GeV), E_safe=max(E,E_floor)
// Two optional energy resolution models around E_mean:
//   MODEL 1 (Simple): E_smeared = Gaus(E_mean, σ × √E_mean)
//     - Data-driven, σ in GeV^(1/2), typically 0.02-0.04
//   MODEL 2 (3-term): E_smeared = Gaus(E_mean, σ × E_mean × √((A/√E_mean)² + (B/E_mean)² + C²))
//     - Physics-motivated with A,B,C constants
// Set USE_SIMPLE_STOCHASTIC_MODEL to choose
// - Position smearing: ADDITIVE X_smeared = X_original + Gaus(0, sigma_pos)
//                              Y_smeared = Y_original + Gaus(0, sigma_pos)
//   Same sigma_pos is used for both x and y positions
// - Smearing parameters loaded from section_map.csv generated by nps_sim_smearing_new_try.C
// - Grid-based section assignment must match nps_sim_smearing_new_try.C
// ============================================================================

